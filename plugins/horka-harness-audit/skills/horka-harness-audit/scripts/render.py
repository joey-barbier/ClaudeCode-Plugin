COST_CHIP = {"free": "c-ok", "minutes": "c-ok", "hours": "c-code", "paid": "c-toi"}
HELD_CHIP = {"nothing": "c-ko", "sentence": "c-code", "script": "c-code", "hook": "c-info", "ci_reports": "c-info",
             "blocks": "c-ok", "na": "c-mut"}
LIMITS = {"summary": 280, "next": 170, "text": 170, "evidence": 130, "title": 90, "stops": 170, "how": 900,
          "note": 120, "gap": 120, "repay_when": 120, "limit": 170, "unsure": 110}


def esc(s):
    """Escape, then turn `code` spans into <code>."""
    return re.sub(r"`([^`]+)`", r"<code>\1</code>", html.escape(str(s), quote=False))


def check(r):
    """Return the list of problems, each one saying how to fix it."""
    e = []

    def text(where, value, key, required=True):
        if value is None or value == "":
            if required:
                e.append(f"{where}: missing. To fix: write it ({LIMITS[key]} characters at most).")
            return
        if not isinstance(value, str):
            e.append(f"{where}: must be text.")
        elif len(value) > LIMITS[key]:
            e.append(f"{where}: {len(value)} characters, {LIMITS[key]} at most. To fix: keep the fact, drop the comment.")

    def count(where, items, lo, hi, of=dict):
        """The list when it has the right size and every item has the right type; else [] and one problem."""
        kind = "an object {...}" if of is dict else "a text"
        if items is None and lo == 0:
            return []
        if not isinstance(items, list) or not lo <= len(items) <= hi:
            n = f"{len(items)} item(s)" if isinstance(items, list) else "not a list"
            e.append(f"{where}: {n}, a list of {lo} to {hi} expected. To fix: keep the ones that weigh most.")
            return []
        bad = [i for i, it in enumerate(items) if not isinstance(it, of)]
        if bad:
            e.append(f"{where}[{bad[0]}]: wrong type. To fix: each item of {where} is {kind}.")
            return []
        return items

    def choice(where, value, allowed, hint):
        if not isinstance(value, str) or value not in allowed:
            e.append(f"{where}: {value!r}. To fix: {hint}.")

    if not isinstance(r, dict):
        return ["the report must be one JSON object {...}. To fix: follow the example in references/report-schema.md."]
    if not isinstance(r.get("lang"), str) or not re.fullmatch(r"[a-z]{2}(-[A-Za-z]{2})?", r["lang"]):
        e.append(f"lang: {r.get('lang')!r}. To fix: the two-letter code of the language of the request (en, fr, de…).")
    text("summary", r.get("summary"), "summary")
    text("title", r.get("title"), "title", required=False)
    text("date", r.get("date"), "note", required=False)
    for i, repo in enumerate(count("repos", r.get("repos"), 1, 6)):
        w = f"repos[{i}]"
        if not isinstance(repo.get("name"), str) or not repo["name"]:
            e.append(f"{w}.name: missing. To fix: the name of the repository, as text.")
        choice(f"{w}.regime", repo.get("regime"), L["en"]["regime"], "production, v1 or experiment")
        for axis in ("design", "detection", "enforcement"):
            v = repo.get(axis)
            if not isinstance(v, int) or isinstance(v, bool) or not 0 <= v <= 3:
                e.append(f"{w}.{axis}: {v!r}. To fix: one whole number from 0 to 3, never a range; between two "
                         "levels take the lower.")
        text(f"{w}.next", repo.get("next"), "next")
        unsure = repo.get("unsure")
        if unsure is not None and not isinstance(unsure, dict):
            e.append(f'{w}.unsure: wrong type. To fix: an object such as {{"detection": "the reason"}}.')
            unsure = None
        for axis, why in (unsure or {}).items():
            if axis not in ("design", "detection", "enforcement"):
                e.append(f"{w}.unsure: {axis!r}. To fix: design, detection or enforcement.")
            text(f"{w}.unsure.{axis}", why, "unsure")
    for side in ("plus", "minus"):
        for i, it in enumerate(count(side, r.get(side), 0, 5)):
            text(f"{side}[{i}].text", it.get("text"), "text")
            text(f"{side}[{i}].evidence", it.get("evidence"), "evidence", required=False)
    for i, a in enumerate(count("actions", r.get("actions"), 0, 6)):
        w = f"actions[{i}]"
        text(f"{w}.title", a.get("title"), "title")
        text(f"{w}.stops", a.get("stops"), "stops")
        text(f"{w}.how", a.get("how"), "how", required=False)
        choice(f"{w}.cost", a.get("cost"), COST_CHIP, "free, minutes, hours or paid")
        choice(f"{w}.target", a.get("target"), L["en"]["target"], "one of " + ", ".join(L["en"]["target"]))
    crit = count("criteria", r.get("criteria"), 12, 72)
    for i, c in enumerate(crit):
        w = f"criteria[{i}]"
        if not isinstance(c.get("id"), str) or not re.fullmatch(r"C([1-9]|1[0-2])", c["id"]):
            e.append(f"{w}.id: {c.get('id')!r}. To fix: C1 to C12.")
        choice(f"{w}.held_by", c.get("held_by"), HELD_CHIP, "one of " + ", ".join(HELD_CHIP))
        text(f"{w}.note", c.get("note"), "note")
        text(f"{w}.repo", c.get("repo"), "note", required=False)
    seen = {c.get("id") for c in crit if isinstance(c.get("id"), str)}
    lack = [f"C{i}" for i in range(1, 13) if f"C{i}" not in seen]
    if crit and lack:
        e.append(f"criteria: {', '.join(lack)} missing. To fix: one line per criterion, `na` when not measured.")
    for i, d in enumerate(count("debt", r.get("debt"), 0, 12)):
        text(f"debt[{i}].gap", d.get("gap"), "gap")
        text(f"debt[{i}].repay_when", d.get("repay_when"), "repay_when")
    for i, s in enumerate(count("limits", r.get("limits"), 0, 8, of=str)):
        text(f"limits[{i}]", s, "limit")
    return e


def meter(t, axis, level, unsure=None):
    cells = "".join(f'<i class="{"on" if i < level else ""}"></i>' for i in range(3))
    return (f'<div class="meter"><div class="lab">{t[axis]}</div><div class="row"><div class="val">{level}<small>/3</small>'
            f'</div><div class="bar l{max(level, 1)}">{cells}</div></div><div class="what">{t[axis + "_w"]}</div>'
            + (f'<div class="unsure"><span class="chip c-mut">{t["unsure"]}</span> {esc(unsure)}</div>' if unsure else "")
            + '</div>')


def levels(r, t):
    out = []
    for repo in r["repos"]:
        ms = "".join(meter(t, a, repo[a], (repo.get("unsure") or {}).get(a)) for a in ("design", "detection", "enforcement"))
        out.append(f'<div class="repo"><div class="name">{esc(repo["name"])}<span class="chip c-mut">'
                   f'{t["regime"][repo["regime"]]}</span></div><div class="meters">{ms}</div>'
                   f'<p class="next"><b>{t["next"]}</b> {esc(repo["next"])}</p></div>')
    return "".join(out)


def plus_minus(r, t):
    out = []
    for side, chip, sign in (("plus", "c-ok", "+"), ("minus", "c-ko", "−")):
        items = "".join(f'<li>{esc(i["text"])}' + (f'<span class="ev">{esc(i["evidence"])}</span>' if i.get("evidence")
                                                    else "") + "</li>" for i in r.get(side) or [])
        items = items or f'<li><span class="ev">{t["none"]}</span></li>'
        out.append(f'<div class="col"><h3><span class="chip {chip}">{sign}</span>{t[side]}</h3><ul>{items}</ul></div>')
    return "".join(out)


def actions(r, t):
    if not r.get("actions"):
        return ""
    out = []
    for n, a in enumerate(r["actions"], 1):
        how = (f'<details><summary>{t["how"]}</summary><pre>{html.escape(a["how"], quote=False)}</pre></details>'
               if a.get("how") else "")
        out.append(f'<div class="act"><div class="n">{n}</div><div class="b"><p class="t">{esc(a["title"])}</p>'
                   f'<div class="chips"><span class="chip {COST_CHIP[a["cost"]]}">{t["cost"][a["cost"]]}</span>'
                   f'<span class="chip c-mut">{t["target"][a["target"]]}</span></div>'
                   f'<p class="stops"><b>{t["stops"]}</b> {esc(a["stops"])}</p>{how}</div></div>')
    return f'<h2>{t["actions"]}</h2><div class="actions">{"".join(out)}</div>'


def probes(scan, t):
    facts = scan.get("facts") if isinstance(scan, dict) and isinstance(scan.get("facts"), list) else []
    rows = [f for f in facts if isinstance(f, dict) and isinstance(f.get("data"), dict)
            and isinstance(f["data"].get("command"), str) and "stopped" in f["data"]]
    if not rows:
        return ""
    multi = len({f.get("scope") for f in rows}) > 1
    body, passing = [], 0
    for f in rows:
        d = f["data"]
        passing += not d["stopped"]
        why = []
        if not d["stopped"] and d.get("hooks_unknown"):
            why.append(t["hook_unknown"].format(n=d["hooks_unknown"]))
        for h in d.get("hooks") or []:          # {"decision": "deny", "name": "guard.sh", "source": "settings.json"}
            if isinstance(h, dict):
                why.append(t["by_hook"].format(kind=h.get("decision", ""), name=f'{h.get("name", "hook")} ({h.get("source", "")})'))
        if d.get("rules") in ("deny", "ask"):
            why.append(t["by_rule"].format(kind=d["rules"], rule=d.get("rule") or ""))
        if not why:
            why.append(t["preapproved"].format(rule=d.get("rule") or "") if d.get("rules") == "allow" else t["no_rule"])
        chip = (f'<span class="chip c-ok">{t["stopped"]}</span>' if d["stopped"]
                else f'<span class="chip c-ko">{t["passes"]}</span>')
        scope = f'<td class="sm">{esc(f.get("scope", ""))}</td>' if multi else ""
        body.append(f'<tr>{scope}<td class="cmd"><code>{html.escape(d["command"], quote=False)}</code></td>'
                    f'<td>{chip}</td><td class="sm">{esc(" · ".join(why))}</td></tr>')
    head = (f'<th>{t["repo"]}</th>' if multi else "") + f'<th>{t["cmd"]}</th><th>{t["verdict"]}</th><th>{t["why"]}</th>'
    count = t["probes_n"].format(passing=passing, total=len(rows))
    return (f'<h2>{t["probes"]}<span class="count">{count}</span></h2><div class="card twrap"><table><thead><tr>{head}'
            f'</tr></thead><tbody>{"".join(body)}</tbody></table></div>')


def criteria(r, t):
    multi = len({c.get("repo") for c in r["criteria"] if c.get("repo")}) > 1
    rows = sorted(r["criteria"], key=lambda c: (int(c["id"][1:]), c.get("repo") or ""))
    body = []
    for c in rows:
        n = int(c["id"][1:])
        repo = f'<td class="sm">{esc(c.get("repo") or "")}</td>' if multi else ""
        body.append(f'<tr><td class="k">{c["id"]} · {t["crit"][n - 1]}</td>{repo}<td><span class="chip {HELD_CHIP[c["held_by"]]}">'
                    f'{t["held"][c["held_by"]]}</span></td><td>{esc(c["note"])}</td></tr>')
    head = f'<th>{t["criterion"]}</th>' + (f'<th>{t["repo"]}</th>' if multi else "") + f'<th>{t["held_by"]}</th><th>{t["note"]}</th>'
    return (f'<h2>{t["criteria"]}</h2><div class="card twrap"><table><thead><tr>{head}</tr></thead>'
            f'<tbody>{"".join(body)}</tbody></table></div>')


def debt(r, t):
    if not r.get("debt"):
        return ""
    body = "".join(f'<tr><td>{esc(d["gap"])}</td><td>{esc(d["repay_when"])}</td></tr>' for d in r["debt"])
    return (f'<h2>{t["debt"]}</h2><div class="card twrap"><table><thead><tr><th>{t["gap"]}</th><th>{t["repay"]}</th>'
            f'</tr></thead><tbody>{body}</tbody></table></div>')


def limits(r, t):
    if not r.get("limits"):
        return ""
    return f'<h2>{t["limits"]}</h2><ul class="limits">{"".join(f"<li>{esc(s)}</li>" for s in r["limits"])}</ul>'


def main():
    ap = argparse.ArgumentParser(description="Render a harness audit as one HTML page.")
    ap.add_argument("report", help="the judgement, as JSON (references/report-schema.md)")
    ap.add_argument("--scan", help="the JSON written by scan.py --json, for the probe table")
    ap.add_argument("--out", help="output file (default: next to the report, same name, .html)")
    ap.add_argument("--open", action="store_true", help="open the page in the default browser")
    args = ap.parse_args()

    try:
        r = json.loads(Path(args.report).read_text())
    except (OSError, ValueError) as err:
        print(f"cannot read {args.report}: {err}. To fix: write valid JSON (references/report-schema.md).")
        return 1
    problems = check(r)
    if problems:
        print(f"{len(problems)} problem(s) in {args.report}; nothing was written:")
        for p in problems:
            print(f"- {p}")
        return 1
    scan = None
    if args.scan:
        try:
            scan = json.loads(Path(args.scan).read_text())
        except (OSError, ValueError) as err:
            print(f"warning: scan file not readable ({err}); the probe table is left out.")
    t = L.get(r["lang"][:2], L["en"])      # labels exist in English and French; other languages get English labels
    title = r.get("title") or t["title"]
    repos = ", ".join(x["name"] for x in r["repos"])
    page = TEMPLATE.read_text()
    for key, value in {
        "LANG": r["lang"], "TITLE": esc(title), "EYEBROW": t["eyebrow"],
        "DATE": esc(r.get("date") or (scan or {}).get("date") or time.strftime("%Y-%m-%d")),
        "TAGLINE": esc(t["scope"].format(repos=repos)), "L_ESSENTIAL": t["essential"], "SUMMARY": esc(r["summary"]),
        "LEVELS": levels(r, t), "PLUS_MINUS": plus_minus(r, t), "ACTIONS": actions(r, t), "PROBES": probes(scan, t),
        "CRITERIA": criteria(r, t), "DEBT": debt(r, t), "LIMITS": limits(r, t), "FOOT": t["foot"],
    }.items():
        page = page.replace("{{" + key + "}}", value)
    out = Path(args.out) if args.out else Path(args.report).with_suffix(".html")
    out.write_text(page)
    print(f"page written: {out}")
    if args.open:
        opener = {"darwin": ["open"], "win32": ["cmd", "/c", "start", ""]}.get(sys.platform, ["xdg-open"])
        try:
            subprocess.run(opener + [str(out)], check=True, capture_output=True, timeout=15)
            print("opened in the browser")
        except (OSError, subprocess.SubprocessError):
            print("could not open a browser here: give the path above to the user")
    return 0


if __name__ == "__main__":
    sys.exit(main())
